#!/usr/bin/env node
// Pack every mod folder (mod.json + mod.js + icons/*.png) into one script, mods-bundle.js, that is injected
// after host-mods.js. Only what is in the package runs: nothing is fetched at play time.
//   node tools/build-mods.mjs [publicDir]      (default: ../public-wip next to this folder)
//   node tools/build-mods.mjs <dir> --check   only check the mods in <dir>/mods, write nothing
// A folder is skipped, with a reason, when mod.json is not valid, the id does not match the folder name,
// or mod.js does not pass `node --check`.
// Icons (接口版本 2): mods/<id>/icons/<name>.png, a PNG of at most 32x32 and 16 KB, name in lowercase letters,
// digits and -. They go into the bundle as data URIs; the engine adds them to the game's item texture. An item
// uses the icon named like its own id, or the one its `icon` field names. A bad icon is left out with a
// warning (the mod still loads; that item shows the "?" icon).
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const args = process.argv.slice(2), checkOnly = args.includes('--check')
const pub = path.resolve(args.find(a => !a.startsWith('--')) || path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'public-wip'))
const dir = path.join(pub, 'mods')
const FIELDS = ['id', 'name', 'version', 'author', 'description']
const ICON_MAX = 32, ICON_BYTES = 16 * 1024, BUNDLE_WARN = 300 * 1024
const PNG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
const out = ['// Generated by tools/build-mods.mjs from mods/*/ (mod.json + mod.js + icons). Do not edit: change the mod and rebuild.']
const done = []
let failed = false

function readIcons(id) {
  const idir = path.join(dir, id, 'icons'), icons = {}
  if (!existsSync(idir) || !statSync(idir).isDirectory()) return icons
  for (const f of readdirSync(idir).sort()) {
    if (f.startsWith('.')) continue
    const warn = why => { console.error(`build-mods: ${id}: icon ${f} left out: ${why}`); failed = true }
    const m = /^([a-z0-9][a-z0-9-]{0,39})\.png$/.exec(f)
    if (!m) { warn('name must be lowercase letters, digits or -, ending in .png'); continue }
    const buf = readFileSync(path.join(idir, f))
    if (buf.length < 33 || !buf.subarray(0, 8).equals(PNG) || buf.toString('latin1', 12, 16) !== 'IHDR') { warn('not a PNG file'); continue }
    const w = buf.readUInt32BE(16), h = buf.readUInt32BE(20)
    if (w > ICON_MAX || h > ICON_MAX) { warn(`${w}x${h}, at most ${ICON_MAX}x${ICON_MAX}`); continue }
    if (buf.length > ICON_BYTES) { warn(`${buf.length} bytes, at most ${ICON_BYTES}`); continue }
    icons[m[1]] = 'data:image/png;base64,' + buf.toString('base64')
  }
  return icons
}

for (const id of readdirSync(dir, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
  const jsonPath = path.join(dir, id, 'mod.json'), jsPath = path.join(dir, id, 'mod.js')
  const skip = why => { console.error(`build-mods: ${id} skipped: ${why}`); failed = true }
  if (!existsSync(jsonPath) || !existsSync(jsPath)) { skip('needs mod.json and mod.js'); continue }
  let mf
  try { mf = JSON.parse(readFileSync(jsonPath, 'utf8')) } catch (e) { skip('mod.json is not valid JSON: ' + e.message); continue }
  if (mf.id !== id) { skip(`"id" in mod.json (${mf.id}) must be the folder name`); continue }
  if (!/^[a-z0-9][a-z0-9-]{2,39}$/.test(id)) { skip('id: 3-40 lowercase letters, digits or -'); continue }
  const missing = FIELDS.filter(f => typeof mf[f] !== 'string' || !mf[f].trim())
  if (missing.length) { skip('mod.json is missing ' + missing.join(', ')); continue }
  if (mf.api != null && ![1, 2, 3].includes(mf.api)) { skip('"api" in mod.json must be 1, 2 or 3'); continue }
  // 接口版本 3: "modes" says where the mod runs, a list of "solo" and "coop" (left out: co-op rooms only)
  if (mf.modes != null && !(Array.isArray(mf.modes) && mf.modes.length && mf.modes.every(m => m === 'solo' || m === 'coop'))) { skip('"modes" in mod.json must be a list of "solo" and "coop"'); continue }
  if (mf.modes != null && mf.modes.includes('solo') && mf.api !== 3) { skip('"modes" with "solo" needs "api": 3'); continue }
  try { execFileSync(process.execPath, ['--check', jsPath], { stdio: 'pipe' }) } catch (e) { skip('mod.js has a syntax error:\n' + String(e.stderr || e.message)); continue }
  const js = readFileSync(jsPath, 'utf8')
  if (!js.includes(`CoopMods.define('${id}'`) && !js.includes(`CoopMods.define("${id}"`)) { skip(`mod.js must call CoopMods.define('${id}', function (api) { ... })`); continue }
  const icons = readIcons(id), n = Object.keys(icons).length
  out.push(`\n// ---- ${id} ${mf.version} ----`, `if (CoopMods.manifest(${JSON.stringify(mf)})) {`)
  if (n) out.push(`if (CoopMods.icons) CoopMods.icons(${JSON.stringify(id)}, ${JSON.stringify(icons, null, 1)});`)
  out.push(js.trimEnd(), '}')
  done.push(`${id} ${mf.version}` + (n ? ` (${n} icons)` : ''))
}
if (checkOnly) console.log(`build-mods: checked ${done.join(', ') || 'no mods'}`)
else {
  const file = path.join(pub, 'mods-bundle.js'), text = out.join('\n') + '\n'
  writeFileSync(file, text)
  execFileSync(process.execPath, ['--check', file])
  const bytes = Buffer.byteLength(text)
  console.log(`build-mods: mods-bundle.js <- ${done.join(', ') || 'no mods'} (${(bytes / 1024).toFixed(1)} KB)`)
  if (bytes > BUNDLE_WARN) { console.error(`build-mods: mods-bundle.js is over ${BUNDLE_WARN / 1024} KB: make the icons smaller`); failed = true }
}
process.exit(failed ? 1 : 0)
