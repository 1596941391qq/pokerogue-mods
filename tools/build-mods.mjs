#!/usr/bin/env node
// Pack every mod folder (mod.json + mod.js) into one script, mods-bundle.js, that is injected after
// host-mods.js. Only what is in the package runs: nothing is fetched at play time.
//   node tools/build-mods.mjs [publicDir]      (default: ../public-wip next to this folder)
//   node tools/build-mods.mjs <dir> --check   only check the mods in <dir>/mods, write nothing
// A folder is skipped, with a reason, when mod.json is not valid, the id does not match the folder name,
// or mod.js does not pass `node --check`.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const args = process.argv.slice(2), checkOnly = args.includes('--check')
const pub = path.resolve(args.find(a => !a.startsWith('--')) || path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'public-wip'))
const dir = path.join(pub, 'mods')
const FIELDS = ['id', 'name', 'version', 'author', 'description']
const out = ['// Generated by tools/build-mods.mjs from mods/*/ (mod.json + mod.js). Do not edit: change the mod and rebuild.']
const done = []
let failed = false
for (const id of readdirSync(dir, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
  const jsonPath = path.join(dir, id, 'mod.json'), jsPath = path.join(dir, id, 'mod.js')
  const skip = why => { console.error(`build-mods: ${id} skipped: ${why}`); failed = true }
  if (!existsSync(jsonPath) || !existsSync(jsPath)) { skip('needs mod.json and mod.js'); continue }
  let mf
  try { mf = JSON.parse(readFileSync(jsonPath, 'utf8')) } catch (e) { skip('mod.json is not valid JSON: ' + e.message); continue }
  if (mf.id !== id) { skip(`"id" in mod.json (${mf.id}) must be the folder name`); continue }
  if (!/^[a-z0-9][a-z0-9-]{2,39}$/.test(id)) { skip('id: 3-40 lowercase letters, digits or -'); continue }
  const missing = FIELDS.filter(f => typeof mf[f] !== 'string' || !mf[f].trim())
  if (missing.length) { skip('mod.json is missing ' + missing.join(', ')); continue }
  try { execFileSync(process.execPath, ['--check', jsPath], { stdio: 'pipe' }) } catch (e) { skip('mod.js has a syntax error:\n' + String(e.stderr || e.message)); continue }
  const js = readFileSync(jsPath, 'utf8')
  if (!js.includes(`CoopMods.define('${id}'`) && !js.includes(`CoopMods.define("${id}"`)) { skip(`mod.js must call CoopMods.define('${id}', function (api) { ... })`); continue }
  out.push(`\n// ---- ${id} ${mf.version} ----`, `if (CoopMods.manifest(${JSON.stringify(mf)})) {`, js.trimEnd(), '}')
  done.push(`${id} ${mf.version}`)
}
if (checkOnly) console.log(`build-mods: checked ${done.join(', ') || 'no mods'}`)
else {
  writeFileSync(path.join(pub, 'mods-bundle.js'), out.join('\n') + '\n')
  execFileSync(process.execPath, ['--check', path.join(pub, 'mods-bundle.js')])
  console.log(`build-mods: mods-bundle.js <- ${done.join(', ') || 'no mods'}`)
}
process.exit(failed ? 1 : 0)
